def _hindi_fonts():
    regular_name = "DeepTraceHindi"
    bold_name = "DeepTraceHindi-Bold"
    registered = set(pdfmetrics.getRegisteredFontNames())
    if regular_name in registered and bold_name in registered:
        return regular_name, bold_name

    windows_collection = Path(r"C:\Windows\Fonts\Nirmala.ttc")
    candidates = []
    if windows_collection.is_file():
        candidates.append((windows_collection, 0, windows_collection, 1))
    candidates.extend([
        (Path("/usr/share/fonts/truetype/noto/NotoSansDevanagari-Regular.ttf"), None,
         Path("/usr/share/fonts/truetype/noto/NotoSansDevanagari-Bold.ttf"), None),
        (Path("/usr/share/fonts/truetype/noto/NotoSansDevanagariUI-Regular.ttf"), None,
         Path("/usr/share/fonts/truetype/noto/NotoSansDevanagariUI-Bold.ttf"), None),
    ])

    for regular_path, regular_index, bold_path, bold_index in candidates:
        if not regular_path.is_file() or not bold_path.is_file():
            continue
        try:
            regular = TTFont(regular_name, str(regular_path), subfontIndex=regular_index, shapable=True)
            bold = TTFont(bold_name, str(bold_path), subfontIndex=bold_index, shapable=True)
            pdfmetrics.registerFont(regular)
            pdfmetrics.registerFont(bold)
            pdfmetrics.registerFontFamily(regular_name, normal=regular_name, bold=bold_name,
                                          italic=regular_name, boldItalic=bold_name)
            return regular_name, bold_name
        except Exception:
            continue
    raise HindiFontUnavailable("Hindi PDF font is unavailable on this server.")


def generate_pdf_report(analysis_result, filename="report.pdf", language="en"):
    language = "hi" if str(language).lower() == "hi" else "en"
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4)
    styles = getSampleStyleSheet()
    normal_font, bold_font = ("Helvetica", "Helvetica-Bold")
    if language == "hi":
        normal_font, bold_font = _hindi_fonts()
    for style_name in ("Normal", "BodyText"):
        styles[style_name].fontName = normal_font
    styles["Title"].fontName = bold_font
    styles["Heading2"].fontName = bold_font
    story = []

    def tr(value):
        value = str(value)
        if language != "hi":
            return value
        translated = _HINDI.get(value)
        if translated:
            return translated
        lip_mismatch = re.match(r"^Lip-audio correlation low \(([\d.]+)\) — possible lip sync mismatch$", value)
        if lip_mismatch:
            return f"होंठ-ऑडियो तालमेल का सहसंबंध कम है ({lip_mismatch.group(1)})—संभवतः होंठों की गति और ऑडियो मेल नहीं खाते।"
        lip_matched = re.match(r"^Lips and audio appear synchronized \(correlation: ([\d.]+)\)$", value)
        if lip_matched:
            return f"होंठों की गति और ऑडियो तालमेल में लगते हैं (सहसंबंध: {lip_matched.group(1)})"
        return value

    def para(value, style="Normal"):
        return Paragraph(escape(tr(value)), styles[style])

    story.append(para("DeepTrace — Forensic Analysis Report", "Title"))
    story.append(para(f"{tr('Generated')}: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"))
    story.append(Spacer(1, 0.3 * inch))

    auth = analysis_result.get("authenticity") or {}
    risk = tr(auth.get("risk", "unknown").upper())
    story.append(para(f"{tr('Overall Authenticity Score')}: {auth.get('score', '—')}% — {tr('Risk')}: {risk}", "Heading2"))
    story.append(Spacer(1, 0.2 * inch))

    forensic = analysis_result.get("forensics")
    if forensic:
        story.append(para("Forensic Details", "Heading2"))
        cell_style = styles["Normal"]
        rows = []
        if analysis_result.get("filename"):
            rows.append([tr("File name"), Paragraph(escape(str(analysis_result["filename"])), cell_style)])
        if analysis_result.get("verdict"):
            score = analysis_result.get("fake_probability", "—")
            cutoff = round(forensic.get("threshold", 0.5) * 100)
            verdict_summary = f"{tr(analysis_result['verdict'])} ({tr('fake score')} {score}, {tr('cutoff')} {cutoff}%)"
            rows.append([tr("Model verdict"), Paragraph(escape(verdict_summary), cell_style)])
        rows += [
            [tr("Video SHA-256"), Paragraph(f"<font size=8>{escape(str(forensic.get('sha256', '')))}</font>", cell_style)],
            [tr("Analyzed at"), Paragraph(escape(str(forensic.get("analyzed_at", ""))), cell_style)],
            [tr("Model version"), Paragraph(escape(str(forensic.get("model_version", ""))), cell_style)],
        ]
        if analysis_result.get("faces_found") is not None:
            rows.append([tr("Frames with a face"), Paragraph(
                f"{analysis_result['faces_found']} / {analysis_result.get('frames_sampled')}", cell_style)])
        table = Table(rows, colWidths=[1.6 * inch, 4.4 * inch])
        table.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F5F5F5")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("PADDING", (0, 0), (-1, -1), 6),
            ("FONTNAME", (0, 0), (-1, -1), normal_font),
        ]))
        story.append(table)
        story.append(Spacer(1, 0.3 * inch))

    story.append(para("Suspicion Breakdown", "Heading2"))
    breakdown = analysis_result.get("breakdown") or {}
    signals = [("Blink Anomaly", breakdown.get("blink")),
               ("Lip Sync Mismatch", breakdown.get("lip_sync")),
               ("Feature Drift", breakdown.get("feature_drift"))]
    table_data = [[tr("Signal"), tr("Score"), tr("Status")]]
    for label, value in signals:
        score = value if value is not None else "—"
        status = ("Suspicious" if isinstance(value, (int, float)) and value > 0.6 else "Normal") if value is not None else "—"
        table_data.append([tr(label), str(score), tr(status)])
    table = Table(table_data, colWidths=[2.5 * inch, 1.5 * inch, 2 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2D2D2D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), bold_font),
        ("FONTNAME", (0, 1), (-1, -1), normal_font),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#F5F5F5"), colors.white]),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(table)
    story.append(Spacer(1, 0.3 * inch))

    story.append(para("Detected Manipulation Segments", "Heading2"))
    segments = analysis_result.get("fake_segments", [])
    if segments:
        segment_data = [[tr("Start Time"), tr("End Time"), tr("Confidence")]]
        for segment in segments:
            segment_data.append([
                f"{segment.get('start', '—')}s",
                f"{segment.get('end', '—')}s",
                f"{round(segment.get('avg_confidence', 0) * 100, 1)}%",
            ])
        table = Table(segment_data, colWidths=[2 * inch, 2 * inch, 2 * inch])
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#C0392B")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), bold_font),
            ("FONTNAME", (0, 1), (-1, -1), normal_font),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#FDECEA"), colors.white]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("PADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(table)
    else:
        story.append(para("No manipulation segments detected."))

    story.append(Spacer(1, 0.3 * inch))
    story.append(para("Analysis Findings", "Heading2"))
    for reason in analysis_result.get("reasons", []):
        story.append(para("• " + reason))

    story.append(Spacer(1, 0.3 * inch))
    audio = analysis_result.get("audio_analysis") or {}
    story.append(para("Audio Analysis", "Heading2"))
    if audio.get("audio_available"):
        audio_table_data = [[tr("Signal"), tr("Score")], [tr("Consistency Score"), str(audio.get("consistency_score", "—"))]]
        audio_table = Table(audio_table_data, colWidths=[3 * inch, 2.5 * inch])
        audio_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2D2D2D")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), bold_font),
            ("FONTNAME", (0, 1), (-1, -1), normal_font),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#F5F5F5"), colors.white]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("PADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(audio_table)
        story.append(Spacer(1, 0.15 * inch))
    audio_reasons = audio.get("audio_reasons") or (["No audio analysis available"] if not audio.get("audio_available") else [])
    for reason in audio_reasons:
        story.append(para("• " + reason))

    story.append(Spacer(1, 0.4 * inch))
    story.append(para("Note: this is a model estimate, not proof. The model was trained on academic datasets and can be wrong on phone, webcam, screen-recorded or heavily compressed video. Blink, mouth-movement and audio checks are rule-based and do not change the verdict."))
    story.append(Spacer(1, 0.2 * inch))
    story.append(para("This report was generated by DeepTrace — Temporal Deepfake Forensic Analyzer"))

    doc.build(story)
    buffer.seek(0)
    return buffer