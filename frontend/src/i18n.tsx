export function getStoredLanguage(): Language {
  return storedLanguage();
}

export function translate(text: string, language: Language = storedLanguage()): string {
  if (language !== "hi") return text;
  const translated = verdictHindi[text] ?? supplementalHi[text] ?? hi[text];
  if (translated) return translated;
  const sizeError = text.match(/^Video is larger than (\d+) MB\.$/);
  if (sizeError) return `वीडियो ${sizeError[1]} MB की सीमा से बड़ा है।`;
  const httpError = text.match(/^Something went wrong \((\d+)\)\.$/);
  if (httpError) return `अनुरोध पूरा नहीं हो सका (${httpError[1]})।`;
  const audioError = text.match(/^Audio analysis failed: (.*)$/);
  if (audioError) return `${supplementalHi["Audio analysis failed: "]}${audioError[1]}`;
  const lipError = text.match(/^Lip sync analysis failed: (.*)$/);
  if (lipError) return `${supplementalHi["Lip sync analysis failed: "]}${lipError[1]}`;
  const lipMismatch = text.match(/^Lip-audio correlation low \(([\d.]+)\) — possible lip sync mismatch$/);
  if (lipMismatch) return `होंठ-ऑडियो तालमेल का सहसंबंध कम है (${lipMismatch[1]})—संभवतः होंठों की गति और ऑडियो मेल नहीं खाते।`;
  const lipMatched = text.match(/^Lips and audio appear synchronized \(correlation: ([\d.]+)\)$/);
  if (lipMatched) return `होंठों की गति और ऑडियो तालमेल में लगते हैं (सहसंबंध: ${lipMatched[1]})`;
  return text;
}

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<Language>(storedLanguage);

  useEffect(() => {
    document.documentElement.lang = language === "hi" ? "hi" : "en";
    try {
      localStorage.setItem(LANGUAGE_KEY, language);
    } catch {
      // Keep the current language for this session when storage is unavailable.
    }
  }, [language]);

  const t = useCallback((text: string) => translate(text, language), [language]);
  const value = useMemo(() => ({ language, setLanguage, t }), [language, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

export function useT(): (text: string) => string {
  return useLanguage().t;
}
